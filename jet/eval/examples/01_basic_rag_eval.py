"""
Basic RAG Evaluation Demo
Shows how to evaluate the final answer generated by a RAG pipeline.
"""

from jet.eval.rag_evaluator import RAGEvaluator


def main():
    # Ensure you have your local Phoenix instance running or set CONFIDENT_BASE_URL
    evaluator = RAGEvaluator(project_name="demo-basic-rag")

    query = "What is the capital of France?"
    context = "Paris is the capital and most populous city of France."
    answer = "The capital of France is Paris."

    print(f"Evaluating query: {query}")
    results = evaluator.evaluate_final_answer(query, answer, context)

    print("\nEvaluation Results:")
    print(f"Faithfulness: {results.get('faithfulness')}")
    print(f"Answer Relevancy: {results.get('answer_relevancy')}")
    print(f"Context Coherence: {results.get('context_coherence')}")


if __name__ == "__main__":
    main()
